CREATE TABLE BV_CIDADAO (
  ID_CIDADAO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOME_EXIBICAO VARCHAR2(100) NOT NULL,
  CRIADO_EM TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE BV_CATEGORIA (
  ID_CATEGORIA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOME VARCHAR2(80) NOT NULL UNIQUE
);
CREATE TABLE BV_OCORRENCIA (
  ID_OCORRENCIA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_CIDADAO NUMBER NOT NULL REFERENCES BV_CIDADAO(ID_CIDADAO),
  ID_CATEGORIA NUMBER NOT NULL REFERENCES BV_CATEGORIA(ID_CATEGORIA),
  TITULO VARCHAR2(90) NOT NULL,
  DESCRICAO VARCHAR2(600) NOT NULL,
  LOCAL_REFERENCIA VARCHAR2(140) NOT NULL,
  STATUS VARCHAR2(20) DEFAULT 'REGISTRADA' NOT NULL,
  CRIADO_EM TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  ATUALIZADO_EM TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT BV_CK_STATUS CHECK (STATUS IN ('REGISTRADA','EM_ANALISE','EM_ATENDIMENTO','RESOLVIDA'))
);
CREATE TABLE BV_HISTORICO (
  ID_HISTORICO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_OCORRENCIA NUMBER NOT NULL REFERENCES BV_OCORRENCIA(ID_OCORRENCIA),
  STATUS_ANTERIOR VARCHAR2(20),
  STATUS_NOVO VARCHAR2(20) NOT NULL,
  ALTERADO_EM TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  OBSERVACAO VARCHAR2(250)
);
CREATE INDEX BV_IX_OCORRENCIA_STATUS ON BV_OCORRENCIA(STATUS);
CREATE INDEX BV_IX_HISTORICO_OCORRENCIA ON BV_HISTORICO(ID_OCORRENCIA);
