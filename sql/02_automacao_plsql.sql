-- Todas as mudanças são realizadas pelas procedures; não conceder UPDATE direto ao aplicativo.
CREATE OR REPLACE PACKAGE BV_PKG_OCORRENCIA AS
  PROCEDURE REGISTRAR(
    P_CIDADAO IN NUMBER, P_CATEGORIA IN NUMBER,
    P_TITULO IN VARCHAR2, P_DESCRICAO IN VARCHAR2,
    P_LOCAL IN VARCHAR2, P_ID OUT NUMBER
  );
  PROCEDURE AVANCAR_STATUS(P_ID IN NUMBER, P_NOVO_STATUS IN VARCHAR2,
                          P_OBSERVACAO IN VARCHAR2 DEFAULT NULL);
  PROCEDURE INDICADORES(P_TOTAL OUT NUMBER, P_ABERTAS OUT NUMBER,
                       P_RESOLVIDAS OUT NUMBER, P_TAXA OUT NUMBER);
END BV_PKG_OCORRENCIA;
/
CREATE OR REPLACE PACKAGE BODY BV_PKG_OCORRENCIA AS
  FUNCTION ORDEM(P_STATUS VARCHAR2) RETURN PLS_INTEGER IS
  BEGIN
    CASE P_STATUS
      WHEN 'REGISTRADA' THEN RETURN 1;
      WHEN 'EM_ANALISE' THEN RETURN 2;
      WHEN 'EM_ATENDIMENTO' THEN RETURN 3;
      WHEN 'RESOLVIDA' THEN RETURN 4;
      ELSE RETURN 0;
    END CASE;
  END;

  PROCEDURE REGISTRAR(
    P_CIDADAO IN NUMBER, P_CATEGORIA IN NUMBER,
    P_TITULO IN VARCHAR2, P_DESCRICAO IN VARCHAR2,
    P_LOCAL IN VARCHAR2, P_ID OUT NUMBER
  ) IS
  BEGIN
    IF LENGTH(TRIM(P_TITULO)) < 5 OR LENGTH(TRIM(P_DESCRICAO)) < 10
       OR LENGTH(TRIM(P_LOCAL)) < 5 THEN
      RAISE_APPLICATION_ERROR(-20001, 'Preencha corretamente os campos da ocorrência');
    END IF;
    INSERT INTO BV_OCORRENCIA(ID_CIDADAO, ID_CATEGORIA, TITULO, DESCRICAO, LOCAL_REFERENCIA)
    VALUES (P_CIDADAO, P_CATEGORIA, TRIM(P_TITULO), TRIM(P_DESCRICAO), TRIM(P_LOCAL))
    RETURNING ID_OCORRENCIA INTO P_ID;
    INSERT INTO BV_HISTORICO(ID_OCORRENCIA, STATUS_ANTERIOR, STATUS_NOVO, OBSERVACAO)
    VALUES (P_ID, NULL, 'REGISTRADA', 'Registro inicial');
    -- COMMIT controlado pelo chamador, permitindo rollback transacional.
  END;

  PROCEDURE AVANCAR_STATUS(P_ID IN NUMBER, P_NOVO_STATUS IN VARCHAR2,
                          P_OBSERVACAO IN VARCHAR2 DEFAULT NULL) IS
    V_ANTERIOR BV_OCORRENCIA.STATUS%TYPE;
  BEGIN
    SELECT STATUS INTO V_ANTERIOR FROM BV_OCORRENCIA
    WHERE ID_OCORRENCIA = P_ID FOR UPDATE;
    IF ORDEM(P_NOVO_STATUS) <> ORDEM(V_ANTERIOR) + 1 THEN
      RAISE_APPLICATION_ERROR(-20002, 'Transição de status não permitida');
    END IF;
    UPDATE BV_OCORRENCIA SET STATUS=P_NOVO_STATUS, ATUALIZADO_EM=SYSTIMESTAMP
    WHERE ID_OCORRENCIA=P_ID;
    INSERT INTO BV_HISTORICO(ID_OCORRENCIA,STATUS_ANTERIOR,STATUS_NOVO,OBSERVACAO)
    VALUES (P_ID,V_ANTERIOR,P_NOVO_STATUS,SUBSTR(P_OBSERVACAO,1,250));
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RAISE_APPLICATION_ERROR(-20003, 'Ocorrência não encontrada');
  END;

  PROCEDURE INDICADORES(P_TOTAL OUT NUMBER, P_ABERTAS OUT NUMBER,
                       P_RESOLVIDAS OUT NUMBER, P_TAXA OUT NUMBER) IS
  BEGIN
    SELECT COUNT(*), NVL(SUM(CASE WHEN STATUS <> 'RESOLVIDA' THEN 1 ELSE 0 END),0),
           NVL(SUM(CASE WHEN STATUS = 'RESOLVIDA' THEN 1 ELSE 0 END),0)
    INTO P_TOTAL, P_ABERTAS, P_RESOLVIDAS FROM BV_OCORRENCIA;
    P_TAXA := CASE WHEN P_TOTAL=0 THEN 0 ELSE ROUND(P_RESOLVIDAS*100/P_TOTAL,2) END;
  END;
END BV_PKG_OCORRENCIA;
