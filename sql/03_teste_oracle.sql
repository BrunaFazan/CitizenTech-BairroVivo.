SET SERVEROUTPUT ON;
DECLARE
  V_CIDADAO NUMBER;
  V_CATEGORIA NUMBER;
  V_ID NUMBER;
  V_TOTAL NUMBER; V_ABERTAS NUMBER; V_RESOLVIDAS NUMBER; V_TAXA NUMBER;
BEGIN
  INSERT INTO BV_CIDADAO(NOME_EXIBICAO) VALUES ('Pessoa de demonstração')
    RETURNING ID_CIDADAO INTO V_CIDADAO;
  SELECT MIN(ID_CATEGORIA) INTO V_CATEGORIA FROM BV_CATEGORIA;
  BV_PKG_OCORRENCIA.REGISTRAR(V_CIDADAO,V_CATEGORIA,'Luminária apagada',
    'Luminária apagada na esquina principal','Rua Exemplo, 100',V_ID);
  BV_PKG_OCORRENCIA.AVANCAR_STATUS(V_ID,'EM_ANALISE','Relato conferido');
  BV_PKG_OCORRENCIA.AVANCAR_STATUS(V_ID,'EM_ATENDIMENTO','Simulação acadêmica');
  BV_PKG_OCORRENCIA.AVANCAR_STATUS(V_ID,'RESOLVIDA','Conclusão simulada');
  BV_PKG_OCORRENCIA.INDICADORES(V_TOTAL,V_ABERTAS,V_RESOLVIDAS,V_TAXA);
  DBMS_OUTPUT.PUT_LINE('ID='||V_ID||' TOTAL='||V_TOTAL||' RESOLVIDAS='||V_RESOLVIDAS||' TAXA='||V_TAXA||'%');
  COMMIT;
END;
/
SELECT O.ID_OCORRENCIA, O.TITULO, O.STATUS, H.STATUS_ANTERIOR, H.STATUS_NOVO
FROM BV_OCORRENCIA O JOIN BV_HISTORICO H ON H.ID_OCORRENCIA = O.ID_OCORRENCIA
ORDER BY O.ID_OCORRENCIA, H.ID_HISTORICO;
